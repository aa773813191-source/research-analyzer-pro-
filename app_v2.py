# ------------------------- Helpers -------------------------
def load_dataset(uploaded_file):
    name = uploaded_file.name.lower()
    if name.endswith(".csv"):
        try:
            return pd.read_csv(uploaded_file)
        except UnicodeDecodeError:
            uploaded_file.seek(0)
            return pd.read_csv(uploaded_file, encoding="latin-1")
    uploaded_file.seek(0)
    return pd.read_excel(uploaded_file)

def numeric_columns(data):
    return data.select_dtypes(include=np.number).columns.tolist()

def p_interpretation(p_value, alpha):
    if pd.isna(p_value):
        return "The p-value could not be calculated for these data."
    if p_value < alpha:
        return (f"The result is statistically significant at α = {alpha:.3f}. "
                "Interpret it together with the effect size, confidence interval, "
                "study design, and practical context.")
    return (f"The result is not statistically significant at α = {alpha:.3f}. "
            "This does not prove that there is no effect or difference.")

def safe_float(value):
    try:
        return float(value)
    except Exception:
        return np.nan

def make_excel(data):
    output = io.BytesIO()
    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        data.to_excel(writer, index=False, sheet_name="Dataset")
    return output.getvalue()

def make_pdf_report(title, lines):
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from xml.sax.saxutils import escape

        output = io.BytesIO()
        doc = SimpleDocTemplate(
            output, pagesize=A4,
            rightMargin=2*cm, leftMargin=2*cm,
            topMargin=1.8*cm, bottomMargin=1.8*cm
        )
        styles = getSampleStyleSheet()
        story = [Paragraph(escape(title), styles["Title"]), Spacer(1, 12)]
        for line in lines:
            story.append(Paragraph(escape(str(line)), styles["BodyText"]))
            story.append(Spacer(1, 7))
        story.append(Spacer(1, 12))
        story.append(Paragraph(
            "Generated by STATNOVA. Interpret findings in the context of the study design.",
            styles["Italic"]
        ))
        doc.build(story)
        return output.getvalue()
    except Exception:
        return None

